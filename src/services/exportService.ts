import JSZip from 'jszip';
import { AnalysisResult, ResourceFile } from '../types';
import { generateCssVariablesExport, generateTailwindExport, generateScssExport } from './colorExtractor';

function triggerBrowserDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadTextFile(content: string, filename: string, mimeType: string = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  triggerBrowserDownload(blob, filename);
}

export function downloadResourceFile(res: ResourceFile) {
  if (!res.content) {
    throw new Error('This resource content was not retrieved over the network.');
  }
  const blob = new Blob([res.content], { type: res.mimeType || 'text/plain' });
  triggerBrowserDownload(blob, res.name);
}

export function generateManifest(analysis: AnalysisResult): object {
  return {
    application: 'ECHO — Website Intelligence Engine',
    brand: 'VR DEVELOPMENTS',
    version: '1.0.0',
    target: {
      url: analysis.targetUrl,
      domain: analysis.metadata.domain,
      title: analysis.metadata.title,
      scannedAt: new Date(analysis.timestamp).toISOString(),
    },
    retrievalAudit: {
      primaryStrategy: analysis.stats.primaryStrategy,
      htmlStatus: analysis.stats.htmlStatus,
      totalDiscovered: analysis.stats.totalDiscovered,
      totalRetrieved: analysis.stats.totalRetrieved,
      totalFailed: analysis.stats.totalFailed,
      totalSizeBytes: analysis.stats.totalSize,
      durationMs: analysis.stats.analysisDurationMs,
    },
    resources: analysis.resources.map(r => ({
      name: r.name,
      url: r.url,
      kind: r.kind,
      status: r.status,
      sizeBytes: r.sizeBytes || null,
      isInline: r.isInline || false,
      strategyUsed: r.strategyUsed || 'N/A',
      errorMessage: r.errorMessage || null,
    })),
    colorsCount: analysis.colors.length,
    headingsCount: analysis.content.headings.length,
    linksCount: analysis.content.links.length,
  };
}

