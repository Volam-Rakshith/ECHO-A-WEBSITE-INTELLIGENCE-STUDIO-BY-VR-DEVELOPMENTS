export async function exportFullZipPackage(analysis: AnalysisResult): Promise<void> {
  const zip = new JSZip();
  const domainClean = analysis.metadata.domain.replace(/[^a-zA-Z0-9_-]/g, '_');
  const root = zip.folder(`echo-export-${domainClean}`);

  if (!root) {
    throw new Error('Failed to create ZIP directory.');
  }

  // 1. Source Folder: Only retrieved or user-supplied files
  const sourceFolder = root.folder('source');
  const stylesFolder = sourceFolder?.folder('stylesheets');
  const scriptsFolder = sourceFolder?.folder('scripts');

  analysis.resources.forEach(res => {
    if (res.content && (res.status === 'RETRIEVED' || res.status === 'USER_PROVIDED')) {
      if (res.kind === 'html') {
        sourceFolder?.file(res.name, res.content);
      } else if (res.kind === 'stylesheet') {
        stylesFolder?.file(res.name, res.content);
      } else if (res.kind === 'script') {
        scriptsFolder?.file(res.name, res.content);
      } else {
        sourceFolder?.file(res.name, res.content);
      }
    }
  });

  // 2. Colors Folder
  const colorsFolder = root.folder('colors');
  colorsFolder?.file('palette.json', JSON.stringify(analysis.colors, null, 2));
  colorsFolder?.file('tokens.css', generateCssVariablesExport(analysis.colors));
  colorsFolder?.file('tailwind.config.js', generateTailwindExport(analysis.colors));
  colorsFolder?.file('_tokens.scss', generateScssExport(analysis.colors));

  // 3. Reports Folder
  const reportsFolder = root.folder('reports');
  reportsFolder?.file('website-info.json', JSON.stringify(analysis.metadata, null, 2));
  reportsFolder?.file('content-analysis.json', JSON.stringify(analysis.content, null, 2));
  reportsFolder?.file('brand-intelligence.json', JSON.stringify(analysis.brand, null, 2));
  reportsFolder?.file('analysis-report.txt', generatePlainTextSummary(analysis));
  reportsFolder?.file('full-intelligence.json', JSON.stringify(analysis, null, 2));

  // 4. Manifest
  const manifest = generateManifest(analysis);
  root.file('retrieval-manifest.json', JSON.stringify(manifest, null, 2));

  // Generate ZIP blob and trigger download
  const blob = await zip.generateAsync({ type: 'blob' });
  triggerBrowserDownload(blob, `echo-${domainClean}-bundle.zip`);
}
